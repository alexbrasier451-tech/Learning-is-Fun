import type { ActivityResponse, ContentIssue, EvaluationResult, FeedbackIssue, TaskDefinition } from '../contracts';
import { canonicalQuestionId } from '../identity';
import { ARITHMETIC_TASKS } from '../../content/expansion-maths/arithmetic';

const record = (value: unknown): value is Record<string, unknown> => value !== null && typeof value === 'object'
  && (Object.getPrototypeOf(value) === Object.prototype || Object.getPrototypeOf(value) === null);
const keys = (value: Record<string, unknown>, expected: readonly string[]) => Object.keys(value).length === expected.length && expected.every(key => Object.hasOwn(value, key));
const integer = (value: unknown, min: number, max: number): value is number => typeof value === 'number' && Number.isSafeInteger(value) && value >= min && value <= max;
// This is JSON structural comparison, not an expression parser. Preserve array
// meaning, but ignore object insertion order and presentation option order.
// Reject undeclared/non-finite values before JSON can erase their type (for
// example, JSON.stringify(NaN) is "null"). Only finite JSON data is content.
function stable(value: unknown): string {
  if (Array.isArray(value)) return `[${Array.from(value, stable).join(',')}]`;
  if (record(value)) return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${stable(value[key])}`).join(',')}}`;
  if (value === null || typeof value === 'string' || typeof value === 'boolean'
    || (typeof value === 'number' && Number.isFinite(value))) return JSON.stringify(value);
  throw new TypeError('Content comparison requires finite JSON values.');
}
function specMeaning(spec: TaskDefinition['responseSpec']): unknown {
  if (spec.kind === 'quantity') return { ...spec, slots: [...spec.slots].sort((a, b) => a.id.localeCompare(b.id)), requiredSlotIds: [...spec.requiredSlotIds].sort() };
  if (spec.kind === 'matching') return { ...spec, items: [...spec.items].sort((a, b) => a.id.localeCompare(b.id)), targets: [...spec.targets].sort((a, b) => a.id.localeCompare(b.id)), requiredItemIds: [...spec.requiredItemIds].sort() };
  if (spec.kind === 'sorting') return { ...spec, items: [...spec.items].sort((a, b) => a.id.localeCompare(b.id)), groups: [...spec.groups].sort((a, b) => a.id.localeCompare(b.id)), requiredItemIds: [...spec.requiredItemIds].sort() };
  return spec;
}
const byId = new Map(ARITHMETIC_TASKS.map(task => [task.canonicalQuestionId, task]));

/** Finite membership is deliberate: unreviewed tuples cannot be silently
 * generated by saved parameters. Reviewed source/help/prompt/stimulus/spec/rule
 * must agree with the authored record. Revision alone is not equivalence. */
export function validateArithmeticTask(task: TaskDefinition): readonly ContentIssue[] {
  const issues: ContentIssue[] = [];
  const id = record(task) && typeof task.canonicalQuestionId === 'string' ? task.canonicalQuestionId : '(unknown)';
  const add = (field: string, code: string, detail: string) => issues.push({ canonicalQuestionId: id, field, code, detail });
  if (!record(task) || !record(task.descriptor)) { add('descriptor', 'descriptor-invalid', 'A task and its finite meaningful descriptor are required.'); return issues; }
  try {
    if (canonicalQuestionId(task.descriptor) !== id) add('canonicalQuestionId', 'identity-mismatch', 'Canonical ID must match the meaningful descriptor.');
  } catch { add('descriptor', 'descriptor-invalid', 'Malformed canonical descriptor.'); return issues; }
  const reviewed = byId.get(id);
  if (!reviewed) { add('descriptor.parameters', 'unreviewed-tuple', 'Only the forty enumerated, reachable r1 tuples are delivered.'); return issues; }
  // Exported records are deeply frozen; reconstructed/untrusted records still
  // traverse every consistency field below.
  if (reviewed === task && issues.length === 0) return issues;
  if (!keys(task, Object.keys(reviewed))) add('task', 'record-shape', 'Reviewed task fields are required; extra fields are not content.');
  if (typeof task.contentRevision !== 'string' || !/^[1-9][0-9]*$/.test(task.contentRevision)) add('contentRevision', 'revision-invalid', 'Content revision is a positive decimal revision string, separate from identity.');
  for (const field of Object.keys(reviewed) as (keyof TaskDefinition)[]) {
    if (field === 'contentRevision') continue;
    try {
      const actual = field === 'responseSpec' ? specMeaning(task.responseSpec) : task[field];
      const expected = field === 'responseSpec' ? specMeaning(reviewed.responseSpec) : reviewed[field];
      if (stable(actual) !== stable(expected)) add(field, 'reviewed-record-mismatch', 'The given parameters, representation, assessed objective and reviewed answers/help must retain their agreed meaning.');
    } catch { add(field, 'malformed-content', 'Content must be finite JSON data in the declared shape.'); }
  }
  return issues;
}

type Draft = { status: 'complete'; response: ActivityResponse } | Extract<EvaluationResult, { status: 'invalid-response' | 'incomplete' }>;
function draft(task: TaskDefinition, response: unknown): Draft {
  const spec = task.responseSpec;
  const field = spec.kind === 'quantity' ? 'values' : spec.kind === 'matching' ? 'pairs' : 'groups';
  const invalid = (reason: string): Draft => ({ status: 'invalid-response', reason });
  if (!record(response) || !keys(response, ['kind', field]) || response.kind !== spec.kind || !record(response[field])) return invalid('Use the declared response kind and semantic value map.');
  const map = response[field];
  const required = spec.kind === 'quantity' ? spec.requiredSlotIds : spec.kind === 'matching' || spec.kind === 'sorting' ? spec.requiredItemIds : [];
  if (Object.keys(map).some(id => !required.includes(id))) return invalid('Unknown slot or item ID.');
  const missing: string[] = [];
  const used = new Set<string>();
  for (const id of required) {
    if (!Object.hasOwn(map, id) || map[id] === null) { missing.push(id); continue; }
    const value = map[id];
    if (spec.kind === 'quantity') {
      const slot = spec.slots.find(row => row.id === id)!;
      if (!record(value) || !keys(value, ['numerator', 'denominator', 'unit'])
        || !integer(value.numerator, slot.numeratorBounds.min, slot.numeratorBounds.max)
        || !integer(value.denominator, 1, 1) || value.unit !== 'count') return invalid(`Slot ${id} requires a bounded whole-number count with denominator 1 and unit count.`);
    } else if (spec.kind === 'matching' || spec.kind === 'sorting') {
      const options = spec.kind === 'matching' ? spec.targets : spec.groups;
      if (typeof value !== 'string' || !options.some(option => option.id === value)) return invalid(`Unknown target or group for ${id}.`);
      if (spec.kind === 'matching' && spec.uniqueTargets && used.has(value)) return invalid('A matching target cannot be used twice.');
      used.add(value);
    } else return invalid('Unsupported arithmetic response form.');
  }
  if (missing.length) return { status: 'incomplete', missing };
  return { status: 'complete', response: response as ActivityResponse };
}

function values(response: ActivityResponse): Record<string, unknown> {
  return response.kind === 'quantity' ? response.values : response.kind === 'matching' ? response.pairs : response.kind === 'sorting' ? response.groups : {};
}
/** Structural-invalid drafts always take precedence over missing fields. Only
 * complete in-domain counts/maps can become judged attempts. No state/UI imports. */
export function evaluateExpansionArithmetic(task: TaskDefinition, response: unknown): EvaluationResult {
  const contentIssues = validateArithmeticTask(task);
  if (contentIssues.length) return { status: 'unavailable-content', issues: contentIssues };
  const parsed = draft(task, response);
  if (parsed.status !== 'complete') return parsed;
  const accepted = task.answerRule.kind === 'accepted-responses' ? task.answerRule.responses : [];
  const actual = values(parsed.response);
  const correct = accepted.some(answer => stable(values(answer)) === stable(actual));
  // Use the closest complete accepted mapping, rather than marking one valid
  // equivalent card wrong merely because it differs from the first alternative.
  const closest = [...accepted].sort((a, b) => {
    const distance = (answer: ActivityResponse) => Object.keys(actual).filter(id => stable(actual[id]) !== stable(values(answer)[id])).length;
    return distance(a) - distance(b);
  })[0];
  const expected = values(closest);
  const issues: FeedbackIssue[] = correct ? [] : Object.keys(actual).filter(id => stable(actual[id]) !== stable(expected[id])).map(id => ({
    code: 'value-mismatch', slotId: id, constraintId: null,
    observed: parsed.response.kind === 'quantity' ? `${id} was set to ${parsed.response.values[id]!.numerator} counters.` : `${id} was placed at ${String(actual[id])}.`,
    explanation: task.responseSpec.kind === 'quantity'
      ? `Check the count requested by “${task.responseSpec.slots.find(slot => slot.id === id)!.label}”. Use the stated operation and check it against the given counts.`
      : 'This placement does not give the expression’s requested total or quotient. Check that expression independently.',
  }));
  return { status: 'judged', correct, canonicalQuestionId: task.canonicalQuestionId, skillId: task.skillId, objectiveId: task.objectiveId, band: task.band,
    feedback: { explanation: task.explanation, issues } };
}
